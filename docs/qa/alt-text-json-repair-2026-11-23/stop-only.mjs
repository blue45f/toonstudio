import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {join} from 'node:path';
import {altRoot, button, openFeature, captureArtwork, currentDocument, dismissCoach, visible, waitUntil} from './helpers.mjs';
import {compareDocument, compareArtwork, assertAbsent, setFixture, startMonitor} from './conduct.mjs';

export async function runStopOnly({page,mock,dir,record,baseline}) {
  const folder = join(dir,'stop-repair-ui');
  await mkdir(folder,{recursive:true});
  const shot = name => page.screenshot({path:join(folder,name+'.png'),timeout:20000});
  const count = (step,n,detail={}) => {
    const messagesPosts = mock.calls.length;
    record(step,{messagesPosts,...detail});
    assert.equal(messagesPosts,n,step);
  };
  const dialog = altRoot(page);
  const run = button(dialog,'설명 만들기');
  const close = async () => {
    await button(dialog,'닫기').click();
    await dialog.waitFor({state:'hidden'});
  };
  const open = async () => {
    await openFeature(page,'alt-text');
    await dialog.waitFor({state:'visible'});
  };
  await open();
  const pixelsBefore=await captureArtwork(page,dialog);
  const img=await setFixture(page,dialog,'A');
  const originalSrc=await img.getAttribute('src');
  const preflight=dialog.locator('[data-claude-preflight] details');
  if (!await preflight.evaluate(el=>el.open)) await preflight.locator('summary').click();
  count('A 실행 전 전송 안내',0,{preflight:await preflight.innerText(),baseline,pixelsBefore});
  await shot('01-실행전-전송안내');
  await preflight.locator('summary').click();
  await startMonitor(dialog,true);
  await run.click();
  await mock.waitForCalls(2);
  await waitUntil(()=>mock.calls[1].responseDisposition==='held','복구 응답 대기');
  const status=dialog.locator('[data-claude-task-status]');
  count('A 한 번 실행 후 복구 보류',2,{status:await status.innerText()});
  const stop=button(dialog,'중단');
  await stop.click();
  await waitUntil(async()=>(await status.innerText()).includes('중단'),'중단 안내');
  const stopped=await status.innerText();
  const receipt=page.waitForResponse(r=>r.url()===new URL('/api/studio-ai/messages',page.url()).href && r.request().method()==='POST',{timeout:30000});
  await mock.releaseRepair();
  const response=await receipt;
  assert.equal(response.status(),200);
  const text=(await response.json()).message.content[0].text;
  assert.equal(JSON.parse(text).short,'QA-A-복구설명');
  await page.waitForTimeout(1500);
  assert.equal(await status.innerText(),stopped);
  assert.equal(await img.getAttribute('src'),originalSrc);
  assert.equal(await img.getAttribute('alt'),'분석할 이미지 미리보기');
  assert.equal(await img.evaluate(i=>i.naturalWidth),96);
  assert.equal(await dialog.locator('[data-claude-alt-result]').count(),0);
  assert.ok(await run.isEnabled());
  await assertAbsent(dialog,'QA-A-복구설명','QA-TRUNCATED-');
  const observed=await page.evaluate(()=>window.__qa4d16RepairMonitorStop());
  assert.equal(observed.staleA,0);
  assert.equal(observed.malformed,0);
  assert.equal(observed.firstShort,null);
  const interim=await currentDocument(page);
  compareDocument(baseline,interim);
  count('A 유지·늦은 응답 수신 후',2,{status:stopped,httpStatus:response.status(),observed,interim});
  await shot('02-A유지-늦은응답후');
  await close();
  await open();
  assert.equal(await dialog.locator('[data-claude-alt-result], img').count(),0);
  const pixelsAfter=await captureArtwork(page,dialog);
  compareArtwork(pixelsBefore,pixelsAfter);
  await close();
  const url=page.url();
  await page.reload({waitUntil:'domcontentloaded'});
  await visible(page.locator('[data-studio-canvas-viewport="true"]')).waitFor({state:'visible',timeout:90000});
  assert.equal(page.url(),url);
  await dismissCoach(page);
  const resume=visible(page.locator('[data-studio-recovery-notice]').getByRole('button',{name:/이어서 그리기|다시 이어 열기|Resume/i}));
  if(await resume.waitFor({state:'visible',timeout:2500}).then(()=>true,()=>false)) await resume.click();
  const reopened=await currentDocument(page);
  compareDocument(baseline,reopened);
  await open();
  assert.equal(await dialog.locator('[data-claude-alt-result], img').count(),0);
  assert.ok(await run.isDisabled());
  const pixelsReopened=await captureArtwork(page,dialog);
  compareArtwork(pixelsBefore,pixelsReopened);
  await shot('03-재열기');
  await close();
  await page.waitForTimeout(750);
  count('A 단독 취소·재열기',2,{reopened,pixelsBefore,pixelsAfter,pixelsReopened});
}
