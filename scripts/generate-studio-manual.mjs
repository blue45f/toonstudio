import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

// S1-7: 매뉴얼 원천 단일화.
// 정본은 인앱 데이터(apps/web/src/domains/creator/manual/studio-manual-data.ts) 하나뿐이고,
// 루트 STUDIO_MANUAL.md 와 STUDIO_3D_DCC_MANUAL.md 는 이 스크립트가 만드는 생성 산출물이다.
// - 생성: node scripts/generate-studio-manual.mjs  (pnpm manual:gen)
// - 검증: node scripts/generate-studio-manual.mjs --check  (pnpm verify:studio-manual-docs)
//   --check 는 파일을 쓰지 않고, 현재 문서가 생성 결과와 한 글자라도 다르면 실패한다(CI 게이트).
// 데이터 모듈은 타입 전용 문법만 쓰므로 Node 24 타입 스트리핑으로 그대로 import 한다(레포 engines >=24.16.0).

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const checkOnly = process.argv.includes("--check");

const dataPath = path.join(repoRoot, "apps/web/src/domains/creator/manual/studio-manual-data.ts");
const { MANUAL_ARTICLES, MANUAL_CATEGORIES, MANUAL_SHORTCUTS, MANUAL_UPDATED } = await import(pathToFileURL(dataPath).href);

const BANNER = "<!-- AUTO-GENERATED by scripts/generate-studio-manual.mjs — do not edit this file directly. -->";

/** GitHub 마크다운 앵커 규칙: 소문자화, 문장부호 제거, 공백→하이픈, 중복 시 -1, -2 접미. */
function createSlugger() {
  const seen = new Map();
  return (text) => {
    const base = text.toLowerCase().replace(/[^\p{L}\p{N} _-]/gu, "").replace(/ /g, "-");
    const count = seen.get(base) ?? 0;
    seen.set(base, count + 1);
    return count === 0 ? base : `${base}-${count}`;
  };
}

function renderArticle(article, slugOf, level) {
  const hashes = "#".repeat(level);
  const lines = [`${hashes} ${article.title}`, "", `> ${article.summary}`, "", `인앱 문서: \`/studio/manual/${article.id}\` · 작업 공간: \`${article.workspace}\``, ""];
  for (const section of article.sections) {
    lines.push(`${hashes}# ${section.title}`, "");
    for (const paragraph of section.paragraphs) lines.push(paragraph, "");
    if (section.steps?.length) {
      section.steps.forEach((step, index) => lines.push(`${index + 1}. ${step}`));
      lines.push("");
    }
    if (section.note) lines.push(`> **참고:** ${section.note}`, "");
  }
  const related = article.related
    .map((id) => MANUAL_ARTICLES.find((entry) => entry.id === id))
    .filter(Boolean)
    .map((entry) => `[${entry.title}](#${slugOf.get(entry.id)})`);
  if (related.length) lines.push(`관련 문서: ${related.join(" · ")}`, "");
  return lines;
}

function renderStudioManual() {
  const slugger = createSlugger();
  slugger("ToonStudio 스튜디오 매뉴얼");
  slugger("목차");
  // 본문 등장 순서대로 앵커를 먼저 확정한다(관련 문서 링크가 앞쪽 문서를 가리킬 수 있다).
  const slugOf = new Map();
  const categorySlugOf = new Map();
  for (const category of MANUAL_CATEGORIES) {
    categorySlugOf.set(category.id, slugger(category.title));
    for (const article of MANUAL_ARTICLES.filter((entry) => entry.category === category.id)) {
      slugOf.set(article.id, slugger(article.title));
      for (const section of article.sections) slugger(section.title);
    }
  }
  slugger("부록: 기본 단축키");

  const lines = [
    BANNER,
    "# ToonStudio 스튜디오 매뉴얼",
    "",
    "> 이 문서는 인앱 매뉴얼(`/studio/manual`)의 정본 데이터 `apps/web/src/domains/creator/manual/studio-manual-data.ts`에서 자동 생성됩니다.",
    "> 내용을 고치려면 인앱 데이터를 수정한 뒤 `pnpm manual:gen`으로 다시 생성하세요. 이 파일을 직접 편집하면 CI의 생성 일치 검증(`pnpm verify:studio-manual-docs`)이 실패합니다.",
    `> 최종 수정: ${MANUAL_UPDATED} · 분류 ${MANUAL_CATEGORIES.length}개 · 문서 ${MANUAL_ARTICLES.length}개`,
    "",
    "## 목차",
    "",
  ];
  for (const category of MANUAL_CATEGORIES) {
    const articles = MANUAL_ARTICLES.filter((entry) => entry.category === category.id);
    lines.push(`- [${category.title}](#${categorySlugOf.get(category.id)})`);
    for (const article of articles) lines.push(`  - [${article.title}](#${slugOf.get(article.id)})`);
  }
  lines.push("");
  for (const category of MANUAL_CATEGORIES) {
    lines.push(`## ${category.title}`, "", category.description, "");
    for (const article of MANUAL_ARTICLES.filter((entry) => entry.category === category.id)) {
      lines.push(...renderArticle(article, slugOf, 3));
    }
  }
  lines.push("## 부록: 기본 단축키", "", "| 단축키 | 동작 |", "| --- | --- |");
  for (const shortcut of MANUAL_SHORTCUTS) lines.push(`| ${shortcut.keys} | ${shortcut.action} |`);
  lines.push("");
  return lines.join("\n");
}

const LEGACY_START = "<!-- legacy-appendix:start -->";
const LEGACY_END = "<!-- legacy-appendix:end -->";

/** 기존 3D 문서에서 보존 원고(부록)를 꺼낸다. 생성본이면 마커 사이를, 원본이면 첫 ## 제목부터 끝까지를 취한다. */
function extractLegacyAppendix(current) {
  const start = current.indexOf(LEGACY_START);
  const end = current.indexOf(LEGACY_END);
  if (start !== -1 && end > start) return current.slice(start + LEGACY_START.length, end).trim();
  const firstHeading = current.indexOf("\n## ");
  const legacyBody = firstHeading === -1 ? current.trim() : current.slice(firstHeading + 1).trim();
  return [
    "## 부록: 기존 3D DCC 상세 가이드 (보존 원고)",
    "",
    "아래는 인앱 정본 전환 전에 별도로 유지되던 3D DCC 상세 가이드 원문입니다. 인앱 매뉴얼에 아직 편입되지 않은",
    "엔진 내부 구조 설명이 포함돼 있어 생성 문서의 부록으로 그대로 보존합니다. 이 부록의 내용만은 예외적으로",
    "이 파일에서 직접 고칠 수 있고, 재생성해도 마커 사이의 내용은 유지됩니다.",
    "",
    legacyBody,
  ].join("\n");
}

function renderThreeManual(currentThreeDoc) {
  const threeArticles = MANUAL_ARTICLES.filter((entry) => entry.category === "three");
  const slugger = createSlugger();
  slugger("ToonStudio 3D 활용 가이드");
  const slugOf = new Map();
  for (const article of threeArticles) {
    slugOf.set(article.id, slugger(article.title));
    for (const section of article.sections) slugger(section.title);
  }
  slugger("부록: 기존 3D DCC 상세 가이드 (보존 원고)");
  const lines = [
    BANNER,
    "# ToonStudio 3D 활용 가이드",
    "",
    "> 이 문서는 인앱 매뉴얼(`/studio/manual`) 정본 데이터의 '3D 활용' 분류에서 자동 생성됩니다.",
    "> 본문(부록 제외)을 고치려면 인앱 데이터를 수정한 뒤 `pnpm manual:gen`으로 다시 생성하세요. 직접 편집하면 CI의 생성 일치 검증(`pnpm verify:studio-manual-docs`)이 실패합니다.",
    "> 전체 매뉴얼은 [STUDIO_MANUAL.md](./STUDIO_MANUAL.md), 사용자가 실제로 여는 정본은 인앱 매뉴얼입니다.",
    `> 최종 수정: ${MANUAL_UPDATED}`,
    "",
  ];
  for (const article of threeArticles) lines.push(...renderArticle(article, slugOf, 2));
  lines.push(LEGACY_START, extractLegacyAppendix(currentThreeDoc), LEGACY_END, "");
  return lines.join("\n");
}

const stale = [];
function sync(targetRelative, contents) {
  const target = path.join(repoRoot, targetRelative);
  if (checkOnly) {
    let current = "";
    try {
      current = readFileSync(target, "utf8");
    } catch {
      // 없는 생성 문서는 그 자체로 불일치다.
    }
    if (current !== contents) stale.push(targetRelative);
    return;
  }
  writeFileSync(target, contents);
  console.log(`generated ${targetRelative}`);
}

const currentThree = (() => {
  try {
    return readFileSync(path.join(repoRoot, "STUDIO_3D_DCC_MANUAL.md"), "utf8");
  } catch {
    return "";
  }
})();

sync("STUDIO_MANUAL.md", renderStudioManual());
sync("STUDIO_3D_DCC_MANUAL.md", renderThreeManual(currentThree));

if (checkOnly) {
  if (stale.length) {
    console.error(`Studio manual docs are out of date with the in-app source (apps/web/src/domains/creator/manual/studio-manual-data.ts): ${stale.join(", ")}`);
    console.error("Run `pnpm manual:gen` and commit the regenerated docs.");
    process.exit(1);
  }
  console.log("Studio manual docs match the in-app source.");
}
