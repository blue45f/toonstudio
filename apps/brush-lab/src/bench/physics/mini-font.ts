export const FONT_WIDTH = 5;
export const FONT_HEIGHT = 7;
/** 글자 사이 간격(px). */
export const FONT_ADVANCE = FONT_WIDTH + 1;

/** 지원 글자(대문자 변환 후). */
export function supportsGlyph(ch: string): boolean {
  return Object.prototype.hasOwnProperty.call(GLYPHS, ch);
}

/** 문자열이 그려질 너비(px). 지원하지 않는 글자는 공백으로 센다. */
export function textWidth(text: string): number {
  return text.length === 0 ? 0 : text.length * FONT_ADVANCE - 1;
}

/**
 * RGBA 버퍼(width × ?)에 글자를 그린다(scale배 확대). 대문자로 바꿔 그리고 지원하지 않는 글자는 건너뛴다(공백 폭은 유지).
 * 버퍼 밖으로 나가는 픽셀은 버린다.
 */
export function drawText(
  data: Uint8ClampedArray,
  width: number,
  height: number,
  x0: number,
  y0: number,
  text: string,
  rgb: readonly [number, number, number] = [20, 20, 20],
  scale = 1,
): void {
  let cx = x0;
  for (const raw of text.toUpperCase()) {
    const glyph = GLYPHS[raw];
    if (glyph) {
      for (let gy = 0; gy < FONT_HEIGHT; gy += 1) {
        const row = glyph[gy] ?? "";
        for (let gx = 0; gx < FONT_WIDTH; gx += 1) {
          if (row[gx] !== "#") continue;
          for (let sy = 0; sy < scale; sy += 1) {
            for (let sx = 0; sx < scale; sx += 1) {
              const px = cx + gx * scale + sx;
              const py = y0 + gy * scale + sy;
              if (px < 0 || py < 0 || px >= width || py >= height) continue;
              const o = (py * width + px) * 4;
              data[o] = rgb[0];
              data[o + 1] = rgb[1];
              data[o + 2] = rgb[2];
              data[o + 3] = 255;
            }
          }
        }
      }
    }
    cx += FONT_ADVANCE * scale;
  }
}
