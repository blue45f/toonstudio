// 표지 서버 변환이 디코드를 허용하는 크기 상한. PNG·JPEG 사전 검사(cover-png-guard.ts 등)와
// 변환(cover-transcode.ts)이 같은 값을 쓰도록 한곳에 둔다.

/**
 * 디코드를 허용하는 최대 화소 수(선언 크기 기준). 압축된 바이트는 작아도 PNG·JPEG 헤더가 수만 x 수만
 * 화소를 선언할 수 있고, image-js 의 decode 는 그 크기만큼 메모리를 할당한다(이미지 폭탄, CWE-409).
 * 실제 표지는 많아야 수백만 화소라 1600만 화소(4000x4000)면 정상 이미지를 막지 않는다.
 * 상한을 넘거나 선언 크기를 읽지 못하면 변환하지 않고 호출부가 원본을 그대로 중계한다.
 */
export const COVER_MAX_DECODE_PIXELS = 16_000_000;

/**
 * PNG 의 압축 해제 후 크기(필터 바이트 포함) 상한. 화소 수 상한만으로는 16비트 RGBA 4000x4000(128MB)처럼
 * 선언대로 정직한 이미지도 큰 메모리를 쓴다. 8비트 RGBA 4000x4000(약 64MB)이 들어가는 크기로 잡는다.
 */
export const COVER_MAX_DECODE_RAW_BYTES = 64 * 1024 * 1024;
