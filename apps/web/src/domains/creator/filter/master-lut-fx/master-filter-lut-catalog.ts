const MASTER_FILTER_BY_ID: ReadonlyMap<MasterFilterId, MasterFilterSpec> = new Map(
  MASTER_FILTER_LUT_CATALOG.map((item) => [item.id, item]),
);

export function getMasterFilterById(id: string): MasterFilterSpec | undefined {
  return MASTER_FILTER_BY_ID.get(id as MasterFilterId);
}

export function getMasterFiltersByCategory(
  category: MasterFilterCategoryFilter,
): readonly MasterFilterSpec[] {
  if (category === "all") return MASTER_FILTER_LUT_CATALOG;
  return MASTER_FILTER_LUT_CATALOG.filter((item) => item.category === category);
}

export function searchMasterFilters(
  category: MasterFilterCategoryFilter,
  query: string,
): readonly MasterFilterSpec[] {
  const scoped = getMasterFiltersByCategory(category);
  const normalized = query.normalize("NFKC").trim().toLowerCase();
  if (!normalized) return scoped;
  const tokens = normalized.split(/\s+/).filter((token) => token.length > 0);
  return scoped.filter((item) => {
    const haystack = [
      item.id,
      item.nameKo,
      item.nameEn,
      item.descriptionKo,
      item.descriptionEn,
      item.algorithmTagKo,
      item.algorithmTagEn,
      ...item.keywords,
    ]
      .join(" ")
      .normalize("NFKC")
      .toLowerCase();
    return tokens.every((token) => haystack.includes(token));
  });
}

