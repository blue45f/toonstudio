/** 테스트·프리뷰용 결정적 RGBA8 텍스처 패치 생성기. */
export function createSyntheticMaterialTexture(
  baseRgb: Rgb01,
  size = 16,
  grainAmplitude = 0.035,
): VrmTextureBuffer {
  const dim = Math.max(4, Math.floor(size));
  const data = new Uint8ClampedArray(dim * dim * 4);
  for (let y = 0; y < dim; y += 1) {
    for (let x = 0; x < dim; x += 1) {
      const wave = Math.sin((x + 1) * 0.7 + (y + 1) * 0.45) * grainAmplitude;
      const off = (y * dim + x) * 4;
      data[off] = Math.round(clamp(baseRgb.r + wave, 0, 1) * 255);
      data[off + 1] = Math.round(clamp(baseRgb.g + wave * 0.85, 0, 1) * 255);
      data[off + 2] = Math.round(clamp(baseRgb.b + wave * 0.75, 0, 1) * 255);
      data[off + 3] = 255;
    }
  }
  return { width: dim, height: dim, data };
}

