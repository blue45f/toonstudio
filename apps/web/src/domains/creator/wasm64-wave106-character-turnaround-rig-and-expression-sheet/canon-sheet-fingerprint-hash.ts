import type { CharacterHeadCanonSheet } from "./loomis-rig-types-and-presets";

export interface CanonSheetFingerprints {
  readonly sha256Hex: string;
  readonly fnv1aHex: string;
  readonly canonicalJsonByteLength: number;
}

